// Builds KOREAN-REVIEW.md: every English string beside its Korean translation,
// page by page, for Dr Kim to check. Run after changing any Korean copy:
//
//   npm run korean-review
//
// Reads the same modules the site renders, so the review always matches the site.
import { writeFileSync, readFileSync } from 'node:fs';
import { ui } from '../src/i18n/ui';
import { home } from '../src/i18n/home';
import { careers } from '../src/i18n/careers';
import { faq } from '../src/lib/faq';
import { faqKo } from '../src/lib/faq.ko';
import { roles } from '../src/lib/careers';

type Row = [where: string, en: string, ko: string];

const text = (html: string) =>
  html
    .replace(/<\/(p|li|h3|div)>/g, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();

/** Walks two objects of the same shape and lists their strings side by side. */
function pairs(en: unknown, ko: unknown, path = ''): Row[] {
  if (typeof en === 'string') return [[path, en, String(ko ?? '')]];
  if (Array.isArray(en)) {
    // Short tuples of fragments (e.g. text around a link) read best joined.
    if (en.every((v) => typeof v === 'string') && en.length <= 3 && path.match(/consultations|languages|slogan|headline|seeMore|cvHint|notice/)) {
      return [[path, en.join('…'), (ko as string[]).join('…')]];
    }
    return en.flatMap((v, i) => pairs(v, (ko as unknown[])?.[i], `${path}[${i + 1}]`));
  }
  if (en && typeof en === 'object') {
    return Object.entries(en).flatMap(([k, v]) =>
      pairs(v, (ko as Record<string, unknown>)?.[k], path ? `${path}.${k}` : k),
    );
  }
  return [];
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (rows: Row[]) =>
  [
    '| Where | English | Korean | OK? |',
    '|---|---|---|---|',
    ...rows
      // Skip settings (language codes) and strings left identical on purpose.
      .filter(([where, en, ko]) => !/switchToLang|mapLang/.test(where) && (en !== ko || /[가-힣]/.test(ko)))
      .map(([where, en, ko]) => `| ${cell(where)} | ${cell(en)} | ${cell(ko)} | |`),
  ].join('\n');

const faqRows: Row[] = [
  ['intro', faq.intro, faqKo.intro],
  ...faq.sections.flatMap((section, s) => [
    [`${section.id}`, section.title, faqKo.sections[s].title] as Row,
    ...section.items.flatMap((item, i) => {
      const ko = faqKo.sections[s].items[i];
      return [
        [`${section.id} Q${i + 1}`, item.question, ko.question] as Row,
        [`${section.id} A${i + 1}`, text(item.answer), text(ko.answer)] as Row,
      ];
    }),
  ]),
  ['closingTitle', faq.closingTitle, faqKo.closingTitle],
  ['closingText', faq.closingText, faqKo.closingText],
  ['note', faq.note, faqKo.note],
];

const roleRows: Row[] = roles.flatMap((role) =>
  role.ko ? pairs({ ...role, slug: undefined, draft: undefined, ko: undefined }, role.ko, role.slug) : [],
);

// Paths are from the repo root, where npm runs the script.
const glossary = readFileSync('scripts/korean-glossary.md', 'utf8');

const doc = `# Korean translation review

Every English string on the Korean pages, beside its Korean translation, for Dr Kim to check before the Korean pages go live. Generated by \`npm run korean-review\` from the site's own copy files, so it always matches the site; please mark changes in the **OK?** column or send corrections, and we'll update the copy and regenerate this file.

- **Register:** polite-warm 해요체 throughout.
- **Pages:** \`/ko/\` (home), \`/ko/faq/\`, \`/ko/careers/\` and the role page. Staging only until signed off.
- **Legal wording:** the careers form notice and consent line (Careers section) should also go to the solicitor.
- **Stays English:** clinic name, addresses, phone, email, fund names, qualifications, study citations.

${glossary}

## Home page

${table(pairs(home.en, home.ko))}

## Shared parts (menu, footer, map, keyword band)

${table(pairs(ui.en, ui.ko))}

## FAQ

${table(faqRows)}

## Careers

${table(pairs(careers.en, careers.ko))}

### Sample role (staging only)

${table(roleRows)}
`;

writeFileSync('KOREAN-REVIEW.md', doc);
console.log('Wrote KOREAN-REVIEW.md');
